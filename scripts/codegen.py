"""Write the TypeScript API client from the FastAPI OpenAPI schema."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import cast

from ceo_api.main import app

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_PATH = ROOT / "apps/web/src/lib/api-client/openapi.json"
INDEX_PATH = ROOT / "apps/web/src/lib/api-client/index.ts"


def schema_text() -> str:
    return json.dumps(app.openapi(), indent=2) + "\n"


def api_title() -> str:
    info_obj = app.openapi().get("info")
    if not isinstance(info_obj, dict):
        return ""
    title = cast(dict[str, object], info_obj).get("title")
    return title if isinstance(title, str) else ""


def index_text() -> str:
    title = api_title()
    return (
        "/** Generated by `just codegen` from the FastAPI OpenAPI schema. Do not edit. */\n"
        f"export const apiTitle = {json.dumps(title)};\n"
    )


def main() -> int:
    check = "--check" in sys.argv
    schema = schema_text()
    index = index_text()
    if check:
        current_schema = SCHEMA_PATH.read_text(encoding="utf-8") if SCHEMA_PATH.exists() else ""
        current_index = INDEX_PATH.read_text(encoding="utf-8") if INDEX_PATH.exists() else ""
        if current_schema != schema or current_index != index:
            print("OpenAPI client is stale. Run `just codegen`.", file=sys.stderr)
            return 1
        print("OpenAPI client is up to date.")
        return 0

    SCHEMA_PATH.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA_PATH.write_text(schema, encoding="utf-8")
    INDEX_PATH.write_text(index, encoding="utf-8")
    print(f"wrote {SCHEMA_PATH.relative_to(ROOT)} and {INDEX_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
